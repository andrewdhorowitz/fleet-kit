#!/usr/bin/env python3
"""The derived property view over a project's publish.json — the ONE
derivation function for the fleet's publish property model (Andrew's
distilled design, approved Oct 30, 2026).

The model stores NOTHING: publish.json markers stay v2-shaped, and
the five properties are computed from the existing fields by this
module — in fleet-kit, the shared layer, written once — so every
consumer (the pull tool, the private-section generator, the public
page build, the gates, the owner editor) reads the same view and no
second derivation can drift from it.

    Publish    marker presence — True iff the repo carries
               publish.json at its root. (There is no stored publish
               bit; Publish=False is encoded as status "private".)
    Tier       from `status`: "public" -> Public; "private" ->
               Private; "demo-only" -> Private (its live surface
               lives on the private section; a public demo is a
               separate project with its own manifest).
    Shelf      `section.group`, verbatim: projects | family |
               shared-infrastructure. This IS the content category —
               one axis, the spec's existing wording (category
               ruling, Oct 29, 2026).
    Family     `section.family_visible` (absent or false -> False).
    Sanitized  the sanitization-gate overlay's per-repo result
               (publish-registry/sanitize-overlay.json, generated by
               pull_sanitize.py) — never read from the marker. A
               hand-set `sanitized` key in a manifest is inert data:
               it is never read here and cannot manufacture
               Sanitized=True. Freshness as built for the overlay:
               a result applies only when the overlay's recorded
               manifest SHA matches the manifest just pulled; a
               stale result is ignored (Sanitized=None) with a
               warning. Repos the gate does not scan (demo-only /
               private postures) have no result: Sanitized=None.

The two non-bypassable rules, with no exception mechanism anywhere
(ForcePublish was dropped Oct 30, 2026, before ever being built):

1. Sanitized=False can never be public-facing — see public_facing():
   a project is public-facing only at Tier=Public with
   Sanitized=True; False AND unknown both fail that test.
2. Family=True forces Tier=Private — enforced at schema validation
   (validate(), via the rule clause in publish.schema.json) and
   again here: derive() refuses the combination rather than
   coercing it. There is no runtime coercion anywhere; a forbidden
   combination is an error to fix in the manifest.

Unknown keys — keys the schema does not declare (a `properties`
block, a stray `force_publish` or `sanitized` key) — are inert:
derive() reads only the fields above, and validate() strips them
before schema validation so they never fail it. find_unknown_keys()
reports them so the pull tool can print them as drift, to be removed
as ordinary manifest maintenance (derivation spec §6).

Stdlib only, like the rest of the gate family; the one exception is
validate(), which imports jsonschema lazily — the same dependency
pull_publish.py already declares. Derivation itself never needs it,
so a stdlib-only consumer (the section generator) can import the
derivation without a package install.

Spec: PUBLISH-MANIFEST-SPEC.md, addendum "the marker property
model..." as distilled Oct 30, 2026; derivation spec
PUBLISH-SCHEMA-V3.md (rewritten as the derivation spec), §2/§4/§6.
"""

import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = ROOT / "publish-registry" / "publish.schema.json"
OVERLAY_PATH = ROOT / "publish-registry" / "sanitize-overlay.json"

# status -> Tier. demo-only derives to Private: the project's live
# surface lives on the private section (derivation spec §2).
TIER_BY_STATUS = {"public": "Public", "private": "Private", "demo-only": "Private"}
# Statuses a family_visible manifest may carry (derivation spec §4).
PRIVATE_POSTURES = ("private", "demo-only")


def load_schema():
    return json.loads(SCHEMA_PATH.read_text())


def load_overlay():
    """The committed sanitize overlay dict, or None if absent."""
    if not OVERLAY_PATH.exists():
        return None
    return json.loads(OVERLAY_PATH.read_text())


# --- unknown keys (drift) -------------------------------------------


def _known_key_levels(schema):
    """(path prefix, known key set) for every object level the schema
    declares properties for. The schema is the single source of truth
    for which keys exist; anything else in a manifest is unknown."""
    props = schema.get("properties") or {}
    levels = [("", set(props))]
    for name in ("public_urls", "section"):
        sub = props.get(name) or {}
        if sub.get("properties"):
            levels.append((name, set(sub["properties"])))
    section = props.get("section") or {}
    audiences = (section.get("properties") or {}).get("link_audiences") or {}
    if audiences.get("properties"):
        levels.append(("section.link_audiences", set(audiences["properties"])))
    also = (section.get("properties") or {}).get("also") or {}
    if (also.get("items") or {}).get("properties"):
        levels.append(("section.also[]", set(also["items"]["properties"])))
    return levels


def find_unknown_keys(manifest, schema):
    """Dotted paths of keys the schema does not declare, e.g.
    "properties", "section.force_publish", "section.also[0].tier".
    Inert by construction — reported as drift, never fatal."""
    if not isinstance(manifest, dict):
        return []
    found = []

    def walk(obj, prefix, known):
        if not isinstance(obj, dict):
            return
        for key in obj:
            if key not in known:
                found.append(f"{prefix}{key}")

    levels = dict(_known_key_levels(schema))
    walk(manifest, "", levels[""])
    walk(manifest.get("public_urls"), "public_urls.", levels.get("public_urls", set()))
    section = manifest.get("section")
    walk(section, "section.", levels.get("section", set()))
    if isinstance(section, dict):
        walk(
            section.get("link_audiences"),
            "section.link_audiences.",
            levels.get("section.link_audiences", set()),
        )
        for i, item in enumerate(section.get("also") or []):
            walk(item, f"section.also[{i}].", levels.get("section.also[]", set()))
    return sorted(found)


def strip_unknown_keys(manifest, schema):
    """A deep copy of the manifest with unknown keys removed, so
    schema validation judges the declared shape only (unknown keys
    are drift, reported separately — not validation failures)."""
    cleaned = copy.deepcopy(manifest)
    for path in find_unknown_keys(manifest, schema):
        parts = path.replace("]", "").replace("[", ".").split(".")
        node = cleaned
        for part in parts[:-1]:
            node = node[int(part)] if part.isdigit() else node[part]
        last = parts[-1]
        if isinstance(node, dict):
            node.pop(last, None)
    return cleaned


# --- validation ------------------------------------------------------


def family_rule_error(manifest):
    """The Family rule (derivation spec §4), stated plainly, or None.

    section.family_visible: true requires a private posture —
    "private" or "demo-only" (both derive Tier=Private). Alongside
    status "public" the combination is forbidden: the forcing
    resolves toward private, never toward public, and it is an error
    to fix in the manifest, not a state to repair in flight.
    """
    if not isinstance(manifest, dict):
        return None
    section = manifest.get("section") or {}
    if section.get("family_visible") is True and manifest.get("status") == "public":
        return (
            "Family rule: section.family_visible is true but status is "
            '"public" — Family=True forces Tier=Private, so status must '
            'be "private" or "demo-only" (derivation spec §4)'
        )
    return None


def validate(manifest, schema):
    """Human-readable validation errors for a manifest ([] = valid).

    Runs the Family-rule pre-check (so that failure names the rule,
    not a schema clause), then the fleet schema via jsonschema over
    the manifest with unknown keys stripped — unknown keys are
    drift (find_unknown_keys), never validation failures.
    """
    if not isinstance(manifest, dict):
        return ["manifest is not a JSON object"]
    import jsonschema

    errors = []
    rule = family_rule_error(manifest)
    if rule:
        errors.append(rule)
    validator = jsonschema.Draft202012Validator(schema)
    for err in sorted(
        validator.iter_errors(strip_unknown_keys(manifest, schema)),
        key=lambda e: list(e.absolute_path),
    ):
        if rule and not list(err.absolute_path):
            # The schema's Family clause failing at the root: the
            # pre-check above already states that rule plainly.
            continue
        path = ".".join(str(p) for p in err.absolute_path) or "(root)"
        errors.append(f"{path}: {err.message}")
    return errors


# --- derivation ------------------------------------------------------


def sanitized(overlay_entry, manifest_sha):
    """(Sanitized value, warning) from one repo's overlay entry.

    True/False only for a FRESH in-scope gate result; None when the
    gate has no applicable result — no entry, an out-of-scope
    posture (demo-only/private content is not a public/demo
    surface), or a stale entry, which is ignored with a warning,
    exactly as the section generator treats it.
    """
    if overlay_entry is None:
        return None, None
    if not overlay_entry.get("in_scope"):
        return None, None
    if manifest_sha is not None and overlay_entry.get("manifest_sha") != manifest_sha:
        return None, (
            "sanitize overlay entry is stale (the manifest has moved "
            "since the gate run); ignoring it"
        )
    status = overlay_entry.get("status")
    if status == "pass":
        return True, None
    if status == "fail":
        return False, None
    return None, None


def derive(manifest, overlay_entry=None, manifest_sha=None):
    """The derived property view for one project.

    `manifest` is the project's publish.json dict, or None when the
    repo carries no marker (Publish=False; every other property is
    None/False — there is nothing to derive from). `overlay_entry`
    is the repo's entry from the sanitize overlay (or None) and
    `manifest_sha` the blob SHA of the manifest just pulled, for the
    overlay freshness check.

    Returns (view, warnings): view has exactly the five properties —
    Publish (bool), Tier ("Public"|"Private"), Shelf (the
    section.group value verbatim, or None when the manifest carries
    no section), Family (bool), Sanitized (True|False|None).

    Raises ValueError on the one forbidden combination (Family=True
    with status "public"): validation reports it first with the
    rule named; derivation refuses it rather than coercing, so no
    consumer of the view can ever see Family=True at Tier=Public.
    """
    if manifest is None:
        return (
            {
                "Publish": False,
                "Tier": None,
                "Shelf": None,
                "Family": False,
                "Sanitized": None,
            },
            [],
        )
    rule = family_rule_error(manifest)
    if rule:
        raise ValueError(rule)
    section = manifest.get("section") or {}
    value, warning = sanitized(overlay_entry, manifest_sha)
    view = {
        "Publish": True,
        "Tier": TIER_BY_STATUS.get(manifest.get("status")),
        "Shelf": section.get("group"),
        "Family": section.get("family_visible") is True,
        "Sanitized": value,
    }
    return view, [warning] if warning else []


def public_facing(view):
    """The Sanitized hard rule as a test: a project may face the
    public only at Tier=Public with Sanitized=True. Sanitized=False
    can never be public-facing — and neither can an unknown result:
    no gate result, no public surface."""
    return view.get("Tier") == "Public" and view.get("Sanitized") is True
